//! Starter configuration files printed by `vec init`, generated from the
//! compiled-in defaults ([`DEFAULTS_TOML`]): every key of the defaults appears
//! commented out with its default value and its documentation, so the
//! templates can never drift from the real defaults. (`contrib/vec.conf`,
//! the file distro packages install, is separate: it carries packaging
//! choices on top of the defaults.)

use std::path::{Path, PathBuf};

use anyhow::{Context, Result, anyhow};
use toml::Value;

use crate::config::{Config, DEFAULTS_TOML, Locations};

/// Values that a userland configuration sets (`vec init --user`).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct UserPaths {
    /// The user's home directory: the only include path.
    pub home: PathBuf,
    /// `[embed] model_search_path`: the system model directories that exist,
    /// then the user's own.
    pub model_search_path: Vec<PathBuf>,
    /// `[database] db_path`.
    pub db_path: PathBuf,
    /// `[daemon] socket`.
    pub socket: PathBuf,
}

impl UserPaths {
    /// The paths for the current user, from the home and data directories
    /// and `locations.toml`.
    ///
    /// # Errors
    ///
    /// The home or data directory cannot be determined (`HOME` unset), or
    /// the compiled-in files cannot be parsed.
    pub fn current() -> Result<Self> {
        let home = dirs::home_dir()
            .ok_or_else(|| anyhow!("cannot determine the home directory (is HOME set?)"))?;
        let data = dirs::data_dir().ok_or_else(|| {
            anyhow!("cannot determine the data directory (is HOME or XDG_DATA_HOME set?)")
        })?;
        let loc = Locations::get()?;
        let system_models = Config::defaults()?.embed.model_search_path;
        Ok(Self::new(home, &data, &loc, &system_models))
    }

    fn new(home: PathBuf, data: &Path, loc: &Locations, system_models: &[PathBuf]) -> Self {
        let model_search_path = system_models
            .iter()
            .filter(|p| p.is_dir())
            .cloned()
            .chain(std::iter::once(data.join(&loc.user_model_dir)))
            .collect();
        Self {
            home,
            model_search_path,
            db_path: data.join(&loc.user_db_path),
            socket: data.join(&loc.user_socket),
        }
    }
}

/// Binaries whose presence means a system-wide vec is installed.
///
/// # Errors
///
/// The compiled-in `locations.toml` cannot be parsed.
pub fn system_binaries() -> Result<Vec<PathBuf>> {
    Ok(Locations::get()?.system_binaries)
}

/// The system-wide configuration file (`vec init | sudo tee /etc/vec.conf`):
/// every default, commented out.
///
/// # Errors
///
/// The compiled-in `locations.toml` cannot be parsed.
pub fn system_template() -> Result<String> {
    let system = Locations::get()?.system;
    let header = format!(
        "# {path} — system-wide vec configuration\n\
         # Generated by `vec init`: every key is shown commented out with its compiled-in\n\
         # default. Uncomment and change only what you need.\n\
         # Install: vec init | sudo tee {path}\n",
        path = system.display()
    );
    Ok(header + &commented_defaults(&[]))
}

/// A userland configuration (`vec init --user`): the defaults commented out,
/// plus the keys of `paths` set.
#[must_use]
pub fn user_template(paths: &UserPaths) -> String {
    let path_value = |p: &Path| Value::String(p.display().to_string());
    let path_list = |ps: &[PathBuf]| Value::Array(ps.iter().map(|p| path_value(p)).collect());
    let overrides = [
        (
            "embed",
            "model_search_path",
            path_list(&paths.model_search_path),
        ),
        (
            "index",
            "include_paths",
            path_list(std::slice::from_ref(&paths.home)),
        ),
        ("database", "db_path", path_value(&paths.db_path)),
        ("daemon", "socket", path_value(&paths.socket)),
    ];
    let header = "# vec userland config — no root required\n\
         # Generated by `vec init --user`: the keys set below point vec at your own\n\
         # directories; every other key is shown commented out with its default.\n\
         # Install: mkdir -p ~/.config/vec && vec init --user > ~/.config/vec/config.toml\n\
         # (read automatically; or pass --config <file>)\n\
         #\n\
         # Automatic indexing (systemd user services): see contrib/user/ and README.md.\n";
    header.to_owned() + &commented_defaults(&overrides)
}

/// [`DEFAULTS_TOML`] without its leading comment block, every key line
/// commented out, and `overrides` (section, key, value) set right after their
/// section header.
fn commented_defaults(overrides: &[(&str, &str, Value)]) -> String {
    let mut out = String::with_capacity(DEFAULTS_TOML.len() * 2);
    // Skip the file's own header (up to the first blank line).
    let body = DEFAULTS_TOML
        .split_once("\n\n")
        .map_or(DEFAULTS_TOML, |(_, rest)| rest);
    for line in body.lines() {
        let trimmed = line.trim_start();
        if line.starts_with('[') {
            out.push_str(line);
            out.push('\n');
            let section = line.trim_matches(|c| c == '[' || c == ']');
            for (_, key, value) in overrides.iter().filter(|(s, _, _)| *s == section) {
                out.push_str(&format!("{key} = {value}\n"));
            }
        } else if trimmed.is_empty() || line.starts_with('#') {
            out.push_str(line);
            out.push('\n');
        } else {
            out.push_str("# ");
            out.push_str(line);
            out.push('\n');
        }
    }
    out
}

/// Check that `text` is a valid configuration layer (used by tests and
/// `vec init` itself before printing).
///
/// # Errors
///
/// `text` is not a valid layer.
pub fn check(text: &str) -> Result<Config> {
    Config::from_toml(text).context("the generated configuration is invalid (a vec bug)")
}

#[cfg(test)]
mod tests {
    use super::*;

    fn test_paths(dir: &Path) -> UserPaths {
        let loc = Locations::get().unwrap();
        UserPaths::new(
            dir.join("home"),
            &dir.join("data"),
            &loc,
            &[dir.join("absent")],
        )
    }

    #[test]
    fn system_template_is_the_defaults() {
        let text = system_template().unwrap();
        let cfg = check(&text).unwrap();
        assert_eq!(cfg.provenance(), Config::defaults().unwrap().provenance());
        // Every default key is present, commented out.
        assert!(text.contains("# chunk_size = 40"));
        assert!(text.contains("# model = \"gte-multilingual-base\""));
    }

    #[test]
    fn contrib_vec_conf_is_a_valid_layer() {
        check(include_str!("../../../contrib/vec.conf")).unwrap();
    }

    #[test]
    fn commented_lines_stay_comments() {
        // Every line is blank, a comment, or a section header (no active key).
        let text = system_template().unwrap();
        for line in text.lines() {
            assert!(
                line.is_empty() || line.starts_with('#') || line.starts_with('['),
                "{line:?}"
            );
        }
    }

    #[test]
    fn user_template_sets_only_the_user_paths() {
        let dir = tempfile::tempdir().unwrap();
        let paths = test_paths(dir.path());
        let cfg = check(&user_template(&paths)).unwrap();
        assert_eq!(cfg.index.include_paths, std::slice::from_ref(&paths.home));
        assert_eq!(
            cfg.embed.model_search_path,
            [dir.path().join("data/vec/models")]
        );
        assert_eq!(cfg.database.db_path, paths.db_path);
        assert_eq!(cfg.daemon.socket, paths.socket);
        let defaults = Config::defaults().unwrap();
        assert_eq!(cfg.embed.model, defaults.embed.model);
        assert_eq!(cfg.index.chunk_size, defaults.index.chunk_size);
    }

    #[test]
    fn user_template_escapes_toml_strings() {
        let dir = tempfile::tempdir().unwrap();
        let mut paths = test_paths(dir.path());
        paths.home = PathBuf::from("/home/we\"ird\\name");
        let cfg = check(&user_template(&paths)).unwrap();
        assert_eq!(cfg.index.include_paths, [paths.home]);
    }

    #[test]
    fn existing_system_model_dirs_come_first() {
        let dir = tempfile::tempdir().unwrap();
        let loc = Locations::get().unwrap();
        let sys = dir.path().join("sys-models");
        std::fs::create_dir(&sys).unwrap();
        let p = UserPaths::new(
            dir.path().into(),
            dir.path(),
            &loc,
            std::slice::from_ref(&sys),
        );
        assert_eq!(p.model_search_path[0], sys);
        assert_eq!(p.model_search_path.len(), 2);
    }
}
